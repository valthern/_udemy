# Caracter de "enter"
mensaje1 = "¡Hola\nMundo!"
print(mensaje1)

# Caracter de "Tabulador"
mensaje2 = "\tJuan Perez"
print("1234567812345678")
print(mensaje2)

# Escapar un caracter especial
mensaje3 = "Ella dijo: \"Hola a todos\", a sus estudiantes"
print(mensaje3)

# Escapar Backslash
mensaje4 = "C:\\Users\\omar\\Documents"
print("Ruta:", mensaje4)

# Cadenas
mensaje5 = r"C:\Users\omar\Documents"
print("Ruta:", mensaje5)